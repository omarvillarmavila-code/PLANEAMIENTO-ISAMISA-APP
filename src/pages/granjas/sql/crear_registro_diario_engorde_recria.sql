grant select, insert on public.registro_diario_engorde_recria to authenticated;
grant usage, select on sequence public.registro_diario_engorde_recria_id_seq to authenticated;
create policy registro_engorde_recria_select_authenticated
  on public.registro_diario_engorde_recria for select to authenticated using (true);
create policy registro_engorde_recria_insert_authenticated
  on public.registro_diario_engorde_recria for insert to authenticated with check (true);

