-- Ejecutar una vez en Supabase SQL Editor.
-- Una fila representa un pesaje individual, no un promedio de lote.
-- Cabecera CSV: fecha,semana_cal,lote,peso_gr,tipo_produccion
-- fecha: YYYY-MM-DD. peso_gr: gramos, decimal con punto, sin comas de miles.
-- tipo_produccion: ENGORDE o RECRIA.
begin;

create table public.pesos_granja_asia (
  id bigint generated by default as identity primary key,
  fecha date not null,
  semana_cal smallint not null check (semana_cal between 1 and 53),
  lote text not null check (lote = upper(btrim(lote)) and lote <> ''),
  peso_gr numeric not null check (peso_gr > 0),
  tipo_produccion text check (tipo_produccion in ('ENGORDE', 'RECRIA')),
  created_at timestamptz not null default now()
);

comment on table public.pesos_granja_asia is
  'Pesajes individuales de Granja Asia, separados por engorde y recria. Pesajes repetidos con la misma fecha, lote y peso pueden ser legitimos.';
comment on column public.pesos_granja_asia.peso_gr is 'Peso individual en gramos.';
comment on column public.pesos_granja_asia.semana_cal is
  'Semana calendario suministrada en el reporte original. No equivale a edad del ave.';
comment on column public.pesos_granja_asia.tipo_produccion is
  'Categoria confirmada por el usuario: ENGORDE o RECRIA. No se deduce del nombre del lote.';

create index pesos_asia_tipo_lote_fecha_idx
  on public.pesos_granja_asia (tipo_produccion, lote, fecha);
create index pesos_asia_fecha_idx on public.pesos_granja_asia (fecha);

alter table public.pesos_granja_asia enable row level security;
grant select, insert on public.pesos_granja_asia to authenticated;
grant usage, select on sequence public.pesos_granja_asia_id_seq to authenticated;
create policy pesos_asia_select_authenticated
  on public.pesos_granja_asia for select to authenticated using (true);
create policy pesos_asia_insert_authenticated
  on public.pesos_granja_asia for insert to authenticated with check (true);

notify pgrst, 'reload schema';
commit;

